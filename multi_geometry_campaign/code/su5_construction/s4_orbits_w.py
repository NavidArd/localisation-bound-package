def perm_of_reflection(X2, r2, key):
    """index permutation of the 6561 classes under sigma_alpha, alpha = r2/2."""
    c = (X2 @ r2) // 4                       # x.alpha
    Y2 = X2 - c[:, None] * r2[None, :]
    return np.array([key[tuple(v)] for v in canon3(Y2)], dtype=np.int64)


def orbits_from_perms(idx, perms):
    """orbits of the group generated by `perms` restricted to the index set `idx`."""
    pos = {int(i): k for k, i in enumerate(idx)}
    seen = np.zeros(len(idx), bool)
    out = []
    for k in range(len(idx)):
        if seen[k]:
            continue
        stack, orb = [int(idx[k])], set()
        while stack:
            j = stack.pop()
            if j in orb:
                continue
            orb.add(j)
            for pm in perms:
                t = int(pm[j])
                if t not in orb:
                    stack.append(t)
        for j in orb:
            if j in pos:
                seen[pos[j]] = True
        out.append(sorted(orb))
    return out


def main():
    t0 = time.time()
    X2 = e8_class_reps()
    key = {tuple(canon3(X2[i])): i for i in range(len(X2))}
    roots8 = np.array([[int(2 * c) for c in r] for r in G5.e8_roots()], dtype=np.int64)

    def sel(cond):
        return np.array([r for r in roots8 if cond(r / 2.0)], dtype=np.int64)

    SR1 = sel(lambda al: abs(sum(al[k] * float(P[k]) for k in range(8)) % 1.0) < 1e-9
              and all(abs(sum(al[k] * float(w[k]) for k in range(8))) < 1e-9
                      for w in W_SM))
    SR2 = sel(lambda al: abs(sum(al[k] * float(P[8 + k]) for k in range(8)) % 1.0) < 1e-9
              and abs(al[0] + al[1]) < 1e-9)
    PERM1 = [perm_of_reflection(X2, r, key) for r in SR1]
    PERM2 = [perm_of_reflection(X2, r, key) for r in SR2]

    b1_ok = np.ones(len(X2), bool)
    for (i, j) in ((0, 1), (1, 2), (3, 4)):
        b1_ok &= (((X2[:, i] - X2[:, j]) // 2) % 3 == 0)
    b2_ok = (((X2[:, 0] + X2[:, 1]) // 2) % 3 == 0)
    b1_idx, b2_idx = np.nonzero(b1_ok)[0], np.nonzero(b2_ok)[0]

    y1 = np.array([int(2 * c) for c in Y6[:8]], dtype=np.int64)
    y2 = np.array([int(2 * c) for c in Y6[8:]], dtype=np.int64)
    nrm = (X2 * X2).sum(1) // 4
    d1 = (X2 @ y1) // 4
    d2 = (X2 @ y2) // 4

    # ---- V1 representatives (orbits of the FULL stabiliser), MI1 + MI3 -------------
    o1 = orbits_from_perms(b1_idx, PERM1)
    o2 = orbits_from_perms(b2_idx, PERM2)
    V1c = []
    for A in o1:
        for B in o2:
            a, b = A[0], B[0]
            if (nrm[a] + nrm[b]) % 6 == 2 and (d1[a] + d2[b]) % 3 == 1:
                V1c.append((a, b, len(A), len(B)))
    print("V1 representatives:", len(V1c), flush=True)

    # ---- bad X/Y roots -------------------------------------------------------------
    allr = G5.e8xe8_roots()

    def fd(u, v):
        return sum(x * y for x, y in zip(u, v))

    loc = [r for r in allr if fd(r, P).denominator == 1]
    smset = set()
    for (i, j) in ((0, 1), (1, 2), (3, 4), (0, 2)):
        for s in (1, -1):
            v = [F(0)] * 16
            v[i], v[j] = F(s), F(-s)
            smset.add(tuple(v))
    bad = [r for r in loc if any(fd(r, w) != 0 for w in W_SM) and tuple(r) not in smset]
    BR = np.array([[int(2 * c) for c in r[:8]] for r in bad], dtype=np.int64)
    RX = (X2 @ BR.T) // 4
    surv = (RX % 3 == 0)
    maskcls = np.zeros(len(X2), dtype=np.int64)
    for k in range(len(bad)):
        maskcls |= (surv[:, k].astype(np.int64) << k)

    # ---- per V1: orbits of W under Stab(V1) ---------------------------------------
    total_orb, rows = 0, []
    reps = []
    for (a, b, sa, sb) in V1c:
        # Stab(V1) generators: reflections with alpha.V1 in Z, i.e. alpha.x = 0 mod 3
        g1 = [pm for r, pm in zip(SR1, PERM1) if ((X2[a] @ r) // 4) % 3 == 0]
        g2 = [pm for r, pm in zip(SR2, PERM2) if ((X2[b] @ r) // 4) % 3 == 0]
        w1 = orbits_from_perms(b1_idx, g1)
        w2 = orbits_from_perms(b2_idx, g2)
        cnt = 0
        for A in w1:
            i1 = A[0]
            if (maskcls[i1] & maskcls[a]) != 0:          # SM-exact needs the bad roots dead
                continue
            for B in w2:
                i2 = B[0]
                if (nrm[i1] + nrm[i2]) % 6 != 0:
                    continue
                if (d1[i1] + d2[i2]) % 3 != 0:
                    continue
                if (((X2[i1] @ X2[a]) // 4 + (X2[i2] @ X2[b]) // 4) % 3) != 0:
                    continue
                cnt += 1
                reps.append((a, b, int(i1), int(i2)))
        total_orb += cnt
        rows.append(dict(v1=(int(a), int(b)), n_W_orbits=cnt,
                         w1_orbits=len(w1), w2_orbits=len(w2)))
        print("  V1 (%d,%d): %d W-orbits  [%d x %d]" % (a, b, cnt, len(w1), len(w2)),
              flush=True)

    res = dict(V1_representatives=len(V1c),
               inequivalent_pairs=total_orb,
               per_V1=rows,
               seconds=round(time.time() - t0, 1))
    with open(os.path.join(S.OUT, "s4_orbits_w.json"), "w") as fh:
        json.dump(res, fh, indent=1)
    np.save(os.path.join(S.OUT, "s4_pairs.npy"), np.array(reps, dtype=np.int64))
    print("INEQUIVALENT (V1, W) pairs over V2 = p :", total_orb)
    print("%.1fs" % (time.time() - t0))


if __name__ == "__main__":
    main()
