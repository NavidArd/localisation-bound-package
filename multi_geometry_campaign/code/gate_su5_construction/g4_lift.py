"""V2 (second half) + V4 -- the lift space over a GIVEN V2 class, enumerated generically.

Run for BOTH inequivalent V2 classes found by g2:
   case A  p = (2/3,2/3,-1/3,-1/3,-1/3,0,0,0 | 1/2,1/2,0,0,0,0,0,0)   [the phase's target]
   case B  p = (7/12,7/12,-5/12,-5/12,-5/12,-1/12,-5/12,7/12 | 0^8)   [NEW]

Reproducing the phase's funnel on case A validates the machinery; case B is the number the
phase's letter does not have.

CONDITIONS (each derived here, none inherited).  V1 = x/3, W3 = W4 = z/3, x, z in Lambda,
only the classes mod 3*Lambda matter for the spectrum.  y := 6 V2 in Lambda, primitive.

  SM   alpha . x = 0 mod 3 and alpha . z = 0 mod 3 for alpha in {e1-e2, e2-e3, e4-e5}
  DEL  Delta . x = 0 mod 3 and Delta . z = 0 mod 3        [the doubling lemma]
  MI1  x^2 = 2 mod 6                                      [class-invariant]
  MI6  z^2 = 0 mod 6                                      [class-invariant]
  MI3  x . y = 1 mod 3      <- necessary AND sufficient for a representative to exist,
  MI5  z . y = 0 mod 3         because y is primitive in the unimodular Lambda so
  MI4  z . x = 0 mod 3         lambda.y runs over all of Z as lambda runs over Lambda
  XY   each of the 12 X/Y roots of the block-1 SU(5) is non-integral on V1 or on W
       (they are all integral on V2 by construction, so nothing else can kill them)

Equivalence: reflections sigma_alpha in the roots alpha with alpha perp W_SM, alpha perp
Delta and alpha . V2 = 0 -- the subgroup of Aut(Lambda) fixing the SM pointwise, fixing
Delta and fixing the target vector.  It acts blockwise and preserves every quantity above
(checked in-script), so orbits factorise over the two E8 blocks.

Output: data/gate_su5_construction/g4_lift_<case>.json  and an orbifolder deck.
"""
from __future__ import annotations

import json
import os
import sys
from collections import defaultdict
from fractions import Fraction as F

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gs_lib as G

# E8 simple roots (even coordinate system), a Z-basis of E8
E8B = [
    [F(1), F(-1), F(0), F(0), F(0), F(0), F(0), F(0)],
    [F(0), F(1), F(-1), F(0), F(0), F(0), F(0), F(0)],
    [F(0), F(0), F(1), F(-1), F(0), F(0), F(0), F(0)],
    [F(0), F(0), F(0), F(1), F(-1), F(0), F(0), F(0)],
    [F(0), F(0), F(0), F(0), F(1), F(-1), F(0), F(0)],
    [F(0), F(0), F(0), F(0), F(0), F(1), F(1), F(0)],
    [F(-1, 2)] * 8,
    [F(0), F(0), F(0), F(0), F(0), F(1), F(-1), F(0)],
]
# The twelve X/Y roots of the block-1 SU(5): +-(e_i - e_j), i in {1,2,3}, j in {4,5}.
# (e_i + e_j is a root of E8 but NOT of the SU(5) generated by e_a - e_b, a,b <= 5.)
XY = []
for i in range(3):
    for j in (3, 4):
        for s in (1, -1):
            v = [F(0)] * 8
            v[i], v[j] = F(s), F(-s)
            XY.append(v)
assert len(XY) == 12 and all(tuple(v) in set(G.e8_roots()) for v in XY)


def check_basis():
    import itertools
    Gm = [[G.dot(a, b) for b in E8B] for a in E8B]
    det = np.linalg.det(np.array([[float(x) for x in r] for r in Gm]))
    assert abs(det - 1.0) < 1e-6, det                     # unimodular
    assert all(G.in_e8(b) for b in E8B)
    assert all(G.dot(b, b) == 2 for b in E8B)
    return Gm


def block_tables(Delta_blk, y_blk, sm_alphas, xy_alphas, stab_roots):
    """for one E8 block: per-class integer invariants and the reflection permutations."""
    n = 6561
    A = np.zeros((n, 8), dtype=np.int64)
    for i in range(n):
        t = i
        for k in range(8):
            A[i, k] = t % 3
            t //= 3
    Gm = np.array([[int(G.dot(a, b)) for b in E8B] for a in E8B], dtype=np.int64)
    # x = A @ E8B ; x.v = A @ (E8B . v)
    def dotvec(v):
        return np.array([int(G.dot(b, v)) for b in E8B], dtype=np.int64)

    out = {}
    out["norm2"] = np.einsum("ij,jk,ik->i", A, Gm, A)          # x^2, exact integer
    out["dy"] = A @ dotvec(y_blk) if y_blk is not None else np.zeros(n, dtype=np.int64)
    out["dDelta"] = (A @ dotvec(Delta_blk)) if Delta_blk is not None \
        else np.zeros(n, dtype=np.int64)
    out["sm"] = np.stack([A @ dotvec(a) for a in sm_alphas], 1) if sm_alphas \
        else np.zeros((n, 0), dtype=np.int64)
    out["xy"] = np.stack([A @ dotvec(a) for a in xy_alphas], 1) if xy_alphas \
        else np.zeros((n, 0), dtype=np.int64)
    out["A"] = A
    out["Gm"] = Gm
    # cross term x.z  =  A_x Gm A_z^T
    # reflection permutations mod 3
    perms = []
    Bmat = np.array([[float(c) for c in b] for b in E8B])
    Binv = np.linalg.inv(Bmat)
    for al in stab_roots:
        M = []
        for b in E8B:
            c = G.dot(b, al)
            im = [x - c * yv for x, yv in zip(b, al)]
            coef = Binv.T @ np.array([float(t) for t in im])
            coefi = np.rint(coef).astype(np.int64)
            assert np.allclose(coef, coefi, atol=1e-6), (coef,)
            M.append(coefi)
        M = np.array(M, dtype=np.int64) % 3
        idx = (A @ M) % 3
        perms.append(idx @ np.array([3 ** k for k in range(8)], dtype=np.int64))
    out["perms"] = perms
    return out


def orbits_from_perms(mask, perms):
    """connected components of the classes selected by `mask` under `perms`."""
    n = len(mask)
    lab = np.arange(n, dtype=np.int64)
    lab[~mask] = -1
    sel = np.flatnonzero(mask)
    if len(sel) == 0:
        return lab, {}
    for _ in range(60):
        old = lab.copy()
        for p in perms:
            q = lab[p]
            m = mask & (q >= 0)
            lab[m] = np.minimum(lab[m], q[m])
        pos = lab >= 0
        lab[pos] = lab[lab[pos]]
        if np.array_equal(old, lab):
            break
    reps = defaultdict(list)
    for i in sel:
        reps[int(lab[i])].append(int(i))
    return lab, reps


def run(case, p, Delta, outtag):
    print("\n" + "=" * 78)
    print("CASE", case, " V2 =", ", ".join(str(x) for x in p))
    print("       Delta =", ", ".join(str(x) for x in Delta),
          " (block %d)" % (1 if any(Delta[:8]) else 2))
    y = [6 * x for x in p]
    assert G.in_lattice(y)
    sm = [G.A3[0][:8], G.A3[1][:8], G.A2L[:8]]
    # stabiliser roots: perp to W_SM, perp to Delta, perp to p
    st1, st2 = [], []
    for r in G.e8_roots():
        v = list(r) + [F(0)] * 8
        if all(G.dot(v, c) == 0 for c in G.SM_CARTAN) and G.dot(v, Delta) == 0 \
                and G.dot(v, p) == 0:
            st1.append(list(r))
        v = [F(0)] * 8 + list(r)
        if all(G.dot(v, c) == 0 for c in G.SM_CARTAN) and G.dot(v, Delta) == 0 \
                and G.dot(v, p) == 0:
            st2.append(list(r))
    print("  stabiliser roots: block1 =", len(st1), " block2 =", len(st2))

    T1 = block_tables(list(Delta[:8]), y[:8], sm, [list(a) for a in XY], st1)
    T2 = block_tables(list(Delta[8:]), y[8:], [], [], st2)

    def blockmask(T, need_sm):
        m = np.ones(6561, dtype=bool)
        if need_sm and T["sm"].shape[1]:
            m &= np.all(T["sm"] % 3 == 0, 1)
        m &= (T["dDelta"] % 3 == 0)
        return m

    m1 = blockmask(T1, True)
    m2 = blockmask(T2, True)
    print("  block-1 classes satisfying SM + Delta:", int(m1.sum()), "of 6561")
    print("  block-2 classes satisfying SM + Delta:", int(m2.sum()), "of 6561")

    i1 = np.flatnonzero(m1)
    i2 = np.flatnonzero(m2)
    n1s, n2s = T1["norm2"][i1], T2["norm2"][i2]
    d1y, d2y = T1["dy"][i1], T2["dy"][i2]
    print("  raw (block1 x block2) product:", len(i1) * len(i2))

    # ---- V1 : x^2 = 2 mod 6 and x.y = 1 mod 3
    NS = (n1s[:, None] + n2s[None, :]) % 6
    DY = (d1y[:, None] + d2y[None, :]) % 3
    v1mask = (NS == 2) & (DY == 1)
    v1pairs = np.argwhere(v1mask)
    print("  V1 space (SM, Delta, MI1, MI3):", len(v1pairs))

    # ---- W : z^2 = 0 mod 6 and z.y = 0 mod 3
    wmask = (NS == 0) & (DY == 0)
    wpairs = np.argwhere(wmask)
    print("  W  space (SM, Delta, MI6, MI5):", len(wpairs))

    # ---- orbit-reduce V1 (blockwise)
    lab1, rep1 = orbits_from_perms(m1, T1["perms"])
    lab2, rep2 = orbits_from_perms(m2, T2["perms"])
    print("  block-1 orbits:", len(rep1), " block-2 orbits:", len(rep2))
    v1orb = set()
    for a, b in v1pairs:
        v1orb.add((int(lab1[i1[a]]), int(lab2[i2[b]])))
    print("  V1 orbit representatives:", len(v1orb))

    # ---- pairs (V1 rep, W) with A6 (XY dead) and MI4 (z.x = 0 mod 3)
    A1 = T1["A"]
    A2 = T2["A"]
    Gm1, Gm2 = T1["Gm"], T2["Gm"]
    xy1 = T1["xy"] % 3
    wi1 = i1[wpairs[:, 0]]
    wi2 = i2[wpairs[:, 1]]
    wxy = xy1[wi1]                                    # (NW, 12)
    total_pairs = 0
    survivors = []
    for (o1, o2) in sorted(v1orb):
        x1i, x2i = o1, o2                             # orbit label = min index member
        xv1 = A1[x1i]
        xv2 = A2[x2i]
        vxy = xy1[x1i]
        dead = (vxy % 3 != 0)[None, :] | (wxy % 3 != 0)
        okxy = np.all(dead, 1)
        cross = ((A1[wi1] @ Gm1 @ xv1) + (A2[wi2] @ Gm2 @ xv2)) % 3
        ok = okxy & (cross == 0)
        total_pairs += int(ok.sum())
        for k in np.flatnonzero(ok):
            survivors.append((x1i, x2i, int(wi1[k]), int(wi2[k])))
    print("  (V1 orbit rep, W) pairs passing XY + MI4:", total_pairs)

    # ---- reduce modulo Stab(V1).  Stab(V1) acts BLOCKWISE, so its orbits on the
    # (z1, z2) index space factorise; canonical labels per block are computed once per
    # V1 representative (6561 entries each) and applied to all survivors in O(1).
    final = []
    allmask = np.ones(6561, dtype=bool)
    stab_cache = {}
    by_v1 = defaultdict(list)
    for (x1i, x2i, z1i, z2i) in survivors:
        by_v1[(x1i, x2i)].append((z1i, z2i))
    for key, zs in by_v1.items():
        x1i, x2i = key
        if key not in stab_cache:
            s1 = [pp for pp in T1["perms"] if pp[x1i] == x1i]
            s2 = [pp for pp in T2["perms"] if pp[x2i] == x2i]
            c1, _ = orbits_from_perms(allmask, s1)
            c2, _ = orbits_from_perms(allmask, s2)
            stab_cache[key] = (c1, c2, len(s1), len(s2))
        c1, c2, ns1, ns2 = stab_cache[key]
        seen = set()
        for (z1i, z2i) in zs:
            canon = (int(c1[z1i]), int(c2[z2i]))
            if canon in seen:
                continue
            seen.add(canon)
            final.append((x1i, x2i, canon[0], canon[1]))
    print("  INEQUIVALENT (V1, W) pairs:", len(final))

    def vec(blk, idx, T):
        a = T["A"][idx]
        v = [F(0)] * 8
        for k in range(8):
            v = [q + int(a[k]) * b for q, b in zip(v, E8B[k])]
        return v

    models = []
    for n, (x1i, x2i, z1i, z2i) in enumerate(final):
        x = vec(1, x1i, T1) + vec(2, x2i, T2)
        z = vec(1, z1i, T1) + vec(2, z2i, T2)
        models.append(dict(idx=n, x=[str(t) for t in x], z=[str(t) for t in z]))
    out = dict(case=case, V2=[str(t) for t in p], Delta=[str(t) for t in Delta],
               n_block1_classes=int(m1.sum()), n_block2_classes=int(m2.sum()),
               n_V1=int(len(v1pairs)), n_W=int(len(wpairs)),
               n_V1_orbits=len(v1orb), n_pairs=total_pairs,
               n_inequivalent=len(final), models=models,
               stab_roots=dict(block1=len(st1), block2=len(st2)))
    json.dump(out, open(os.path.join(G.OUT, "g4_lift_%s.json" % outtag), "w"), indent=1)
    print("  wrote g4_lift_%s.json" % outtag)
    return out


def main():
    check_basis()
    g2 = json.load(open(os.path.join(G.OUT, "g2_classes.json")))
    for r in g2["representatives"]:
        p = [G.rat(x) for x in r["p"]]
        # pick a Delta for this class
        if r["n_Delta_block2"]:
            D = next(list(rr) for rr in G.e8_roots() if abs(G.dot(p[8:], rr)) == 1)
            D = [F(0)] * 8 + [x * (1 if G.dot(p[8:], D) == 1 else -1) for x in D]
        else:
            perp = [list(rr) for rr in G.e8_roots()
                    if all(G.dot(list(rr) + [F(0)] * 8, c) == 0 for c in G.SM_CARTAN)]
            D = next(rr for rr in perp if abs(G.dot(p[:8], rr)) == 1)
            D = [x * (1 if G.dot(p[:8], D) == 1 else -1) for x in D] + [F(0)] * 8
        assert G.dot(p, D) == 1 and G.n2(D) == 2
        run(r["case"], p, D, r["case"])


if __name__ == "__main__":
    main()
