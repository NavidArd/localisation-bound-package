# comarks a_i^vee, Bourbaki ordering as produced by `_order_component` below.
def _order_component(comp, adj, simple):
    """Order the nodes of one component in Bourbaki order and return (kind, rank, order)."""
    kind, r = _classify(comp, adj, simple)
    cs = set(comp)
    deg = {i: len(adj[i] & cs) for i in comp}
    if kind == "A":
        if r == 1:
            return kind, r, list(comp)
        ends = [i for i in comp if deg[i] == 1]
        order, prev, cur = [ends[0]], None, ends[0]
        while len(order) < r:
            nxt = [m for m in adj[cur] & cs if m != prev]
            prev, cur = cur, nxt[0]
            order.append(cur)
        return kind, r, order
    b = [i for i in comp if deg[i] >= 3][0]
    legs = []
    for start in adj[b] & cs:
        chain, prev, cur = [start], b, start
        while True:
            nxt = [m for m in adj[cur] & cs if m != prev]
            if not nxt:
                break
            prev, cur = cur, nxt[0]
            chain.append(cur)
        legs.append(chain)
    legs.sort(key=len)
    if kind == "D":
        # Bourbaki D_r: 1-2-...-(r-2) then the two forks r-1, r
        tail = legs[2]                      # the long leg
        order = list(reversed(tail)) + [b] + [legs[0][0], legs[1][0]]
        return kind, r, order
    # E_r: node 2 is the short (length-1) leg; chain 1-3-4-5-...
    short = legs[0][0]
    mid = legs[1]                            # length 2
    lng = legs[2]
    order = [mid[-1], short, mid[0], b] + lng
    return kind, r, order


def comarks(kind, r):
    """a_i^vee in the Bourbaki order used by `_order_component`."""
    if kind == "A":
        return [1] * r
    if kind == "D":
        return [1] + [2] * (r - 3) + [1, 1, 1] if r >= 4 else [1] * r
    if r == 6:
        return [1, 2, 2, 3, 2, 1]
    if r == 7:
        return [2, 2, 3, 4, 3, 2, 1]
    return [2, 3, 4, 6, 5, 4, 3, 2]


def attach_orders(g):
    """Attach the Bourbaki node ordering to each factor of an `analyse_group` result."""
    if not g["factors"]:
        return g
    _, adj = _components(g["simple"])
    for f in g["factors"]:
        kind, r, order = _order_component(f["idx"], adj, g["simple"])
        f["order"] = order
    return g


def dynkin_labels(p, simple_ordered):
    return [dot(p, a) for a in simple_ordered]


def to_dominant(lab, simple_ordered):
    """Weyl-conjugate Dynkin labels into the dominant chamber.  Simply laced, so the
    reflection at node i sends lambda -> lambda - lambda_i * alpha_i, i.e.
    lambda_j -> lambda_j - lambda_i * C_ij with C the Cartan matrix."""
    n = len(simple_ordered)
    C = [[dot(simple_ordered[i], simple_ordered[j]) for j in range(n)] for i in range(n)]
    lab = list(lab)
    for _ in range(4000):
        i = next((k for k in range(n) if lab[k] < 0), None)
        if i is None:
            return lab
        li = lab[i]
        for j in range(n):
            lab[j] -= li * C[i][j]
    raise RuntimeError("Weyl conjugation did not terminate")


_NAMED = {
    ("A", 4, (0, 1, 0, 0)): "10", ("A", 4, (0, 0, 1, 0)): "10bar",
    ("A", 4, (1, 0, 0, 0)): "5", ("A", 4, (0, 0, 0, 1)): "5bar",
    ("A", 4, (0, 0, 0, 0)): "1",
}


def rep_of(p, fac, simple):
    """Local irrep of weight p under simple factor `fac`.  Returns dict."""
    comp = fac["order"]
    so = [simple[i] for i in comp]
    lab = dynkin_labels(p, so)
    if any(x.denominator != 1 for x in lab):
        return dict(ok=False, reason="non-integral Dynkin labels", labels=[str(x) for x in lab])
    lab = [int(x) for x in lab]
    hw = [int(x) for x in to_dominant(lab, so)]
    cm = comarks(fac["kind"], fac["rank"])
    lev = int(sum(a * b for a, b in zip(cm, hw)))
    key = (fac["kind"], fac["rank"], tuple(hw))
    return dict(ok=True, hw=tuple(hw), level=lev, level1_ok=(lev <= 1),
                name=_NAMED.get(key), dim=None)


def proj_norm2(p, basis):
    """|P_W p|^2 where W = span(basis).  Exact over Q (Gram system, Gaussian elimination).

    Used to obtain the SM-Cartan weight norm |w|^2 of a state by EXPLICIT projection onto
    span(SU(3)_c simple roots, SU(2)_L simple root, t_Y) -- never assumed from k_Y (5.21).
    """
    n = len(basis)
    if n == 0:
        return F(0)
    G = [[dot(basis[i], basis[j]) for j in range(n)] for i in range(n)]
    b = [dot(basis[i], p) for i in range(n)]
    A = [row[:] + [b[i]] for i, row in enumerate(G)]
    piv, r = [], 0
    for c in range(n):
        pr = next((i for i in range(r, n) if A[i][c] != 0), None)
        if pr is None:
            continue
        A[r], A[pr] = A[pr], A[r]
        pv = A[r][c]
        A[r] = [x / pv for x in A[r]]
        for i in range(n):
            if i != r and A[i][c] != 0:
                f = A[i][c]
                A[i] = [x - f * y for x, y in zip(A[i], A[r])]
        piv.append(c)
        r += 1
    x = [F(0)] * n
    for i, c in enumerate(piv):
        x[c] = A[i][n]
    return sum(x[i] * b[i] for i in range(n))


