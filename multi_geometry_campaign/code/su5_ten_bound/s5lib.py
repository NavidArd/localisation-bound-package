def _span_basis(vecs):
    """Row-reduce over Q; return (rank, list of pivot rows as basis)."""
    rows = [list(v) for v in vecs]
    basis = []
    piv = []
    for r in rows:
        w = list(r)
        for b, p in zip(basis, piv):
            if w[p]:
                f = F(w[p], 1) / b[p]
                w = [x - f * y for x, y in zip(w, b)]
        nz = next((i for i, x in enumerate(w) if x), None)
        if nz is not None:
            basis.append(w)
            piv.append(nz)
    return len(basis), basis


def simple_roots(roots):
    """Simple roots of a (reduced, simply-laced) root system given as a full root list.

    Positive half chosen by a generic linear functional; a positive root is simple iff it
    is not the sum of two positive roots.
    """
    if not roots:
        return []
    n = len(roots[0])
    # generic functional: rationally independent-ish weights, checked for no zeros
    for seed in range(1, 60):
        f = [F(seed ** (i + 1) + 3 * i + 1, 7 ** (i + 1)) for i in range(n)]
        if all(dot(f, a) != 0 for a in roots):
            break
    else:
        raise RuntimeError("no generic functional found")
    pos = [a for a in roots if dot(f, a) > 0]
    S = set(pos)
    simple = []
    for a in pos:
        if not any((tuple(x - y for x, y in zip(a, b)) in S) for b in pos
                   if b != a and dot(f, b) < dot(f, a)):
            simple.append(a)
    return simple


def _components(simple):
    """Connected components of the Dynkin diagram of `simple`."""
    n = len(simple)
    adj = {i: set() for i in range(n)}
    for i in range(n):
        for j in range(i + 1, n):
            if dot(simple[i], simple[j]) != 0:
                adj[i].add(j)
                adj[j].add(i)
    seen, comps = set(), []
    for i in range(n):
        if i in seen:
            continue
        st, c = [i], []
        seen.add(i)
        while st:
            k = st.pop()
            c.append(k)
            for m in adj[k]:
                if m not in seen:
                    seen.add(m)
                    st.append(m)
        comps.append(sorted(c))
    return comps, adj


def _classify(comp, adj, simple):
    """Return ('A'|'D'|'E', rank) for one connected simply-laced component."""
    r = len(comp)
    if r == 1:
        return ("A", 1)
    deg = {i: len(adj[i] & set(comp)) for i in comp}
    ends = [i for i in comp if deg[i] == 1]
    branch = [i for i in comp if deg[i] >= 3]
    if not branch:
        return ("A", r)
    if len(branch) != 1:
        raise ValueError("not a Dynkin diagram: %d branch nodes" % len(branch))
    b = branch[0]
    if deg[b] != 3:
        raise ValueError("node of degree %d" % deg[b])
    # lengths of the three legs from the branch node
    legs = []
    for start in adj[b] & set(comp):
        L, prev, cur = 1, b, start
        while True:
            nxt = [m for m in adj[cur] & set(comp) if m != prev]
            if not nxt:
                break
            prev, cur = cur, nxt[0]
            L += 1
        legs.append(L)
    legs.sort()
    if legs[0] == 1 and legs[1] == 1:
        return ("D", r)
    if legs == [1, 2, 2]:
        return ("E", 6)
    if legs == [1, 2, 3]:
        return ("E", 7)
    if legs == [1, 2, 4]:
        return ("E", 8)
    raise ValueError("unknown simply-laced diagram, legs=%s" % legs)


def group_name(kind, r):
    if kind == "A":
        return "SU(%d)" % (r + 1)
    if kind == "D":
        return "SO(%d)" % (2 * r)
    return "E%d" % r


def analyse_group(V, roots=None):
    """Full description of the local gauge group at local shift V.

    Returns dict with: n_roots, rank_ss, factors [(name, kind, rank, [simple root idx])],
    simple (list of simple root vectors), comps.
    """
    LR = local_roots(V, roots)
    if not LR:
        return dict(n_roots=0, rank_ss=0, factors=[], simple=[], comp_idx=[],
                    name="U(1)^16")
    S = simple_roots(LR)
    comps, adj = _components(S)
    facs = []
    for c in comps:
        kind, r = _classify(c, adj, S)
        facs.append(dict(name=group_name(kind, r), kind=kind, rank=r, idx=c))
    rank_ss = len(S)
    nm = " x ".join(sorted((f["name"] for f in facs))) or "-"
    if rank_ss < 16:
        nm += " x U(1)^%d" % (16 - rank_ss)
    return dict(n_roots=len(LR), rank_ss=rank_ss, factors=facs, simple=S,
                comps=comps, name=nm)


