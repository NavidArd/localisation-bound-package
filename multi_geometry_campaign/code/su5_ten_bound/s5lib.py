def e8_roots():
    """The 240 roots of one E8 in the even coordinate system (norm^2 = 2)."""
    R = []
    for i in range(8):
        for j in range(i + 1, 8):
            for si in (1, -1):
                for sj in (1, -1):
                    v = [F(0)] * 8
                    v[i] = F(si)
                    v[j] = F(sj)
                    R.append(tuple(v))
    for bits in range(256):
        s = [(-1) ** ((bits >> k) & 1) for k in range(8)]
        if s.count(-1) % 2 == 0:
            R.append(tuple(F(x, 2) for x in s))
    return R


_E8R = None
_E8xE8R = None


def e8xe8_roots():
    """The 480 roots of E8 x E8 as 16-vectors."""
    global _E8R, _E8xE8R
    if _E8xE8R is None:
        _E8R = e8_roots()
        z = (F(0),) * 8
        _E8xE8R = [r + z for r in _E8R] + [z + r for r in _E8R]
    return _E8xE8R


def dot(u, v):
    return sum(a * b for a, b in zip(u, v))


def in_e8(v):
    """v (8 rationals) in Lambda_{E8}?"""
    fr = [x - int(x) if x >= 0 else x - (int(x) - 1) if x != int(x) else F(0) for x in v]
    fr = [x % 1 for x in v]
    if all(x == 0 for x in fr):
        pass
    elif all(x == F(1, 2) for x in fr):
        pass
    else:
        return False
    return sum(v) % 2 == 0


def in_lattice(v):
    return in_e8(v[:8]) and in_e8(v[8:])


def reduce_mod_lattice(v):
    """Canonical representative of v mod Lambda_{E8} x Lambda_{E8}.

    Uses the coset structure Lambda_{E8} = D8 union (D8 + s).  Returns a tuple of
    Fractions in [0,1) per component together with a parity bit per E8 factor, packaged
    as a hashable key; two vectors have the same key iff they differ by a lattice vector.
    """
    key = []
    for h in (0, 8):
        blk = [x % 1 for x in v[h:h + 8]]
        # D8 = integer vectors of even sum; Lambda = D8 u (D8+s), s = (1/2)^8.
        # v mod Lambda is determined by (frac parts) modulo the two generators
        # (1,1,0,...,0) [handled by the %1] and s.  So the residue class is the pair
        # {frac(v), frac(v+s)} together with the sum-parity of the integer part.
        alt = [(x + F(1, 2)) % 1 for x in blk]
        s0 = sum(x for x in v[h:h + 8])
        # parity of (v - frac(v)) . (1,...,1) matters only for the D8 even-sum condition
        p0 = int((s0 - sum(blk)) ) % 2
        p1 = int((s0 + 4 - sum(alt))) % 2
        key.append(min((tuple(blk), p0), (tuple(alt), p1)))
    return tuple(key)


def local_roots(V, roots=None):
    """{alpha in roots(E8xE8) : alpha . V in Z}.  Depends only on V mod Lambda (C2)."""
    if roots is None:
        roots = e8xe8_roots()
    return [a for a in roots if dot(a, V).denominator == 1]


