def selftest(verbose=True):
    out = {}
    R = e8_roots()
    out["e8_root_count"] = len(R)
    assert len(R) == 240, len(R)
    assert all(dot(a, a) == 2 for a in R)
    assert all(in_e8(a) for a in R)
    RR = e8xe8_roots()
    out["e8xe8_root_count"] = len(RR)
    assert len(RR) == 480

    # V = 0 must give back all of E8xE8
    g0 = analyse_group([F(0)] * 16)
    out["V0_group"] = g0["name"]
    out["V0_nroots"] = g0["n_roots"]
    assert g0["n_roots"] == 480 and g0["rank_ss"] == 16
    assert sorted(f["name"] for f in g0["factors"]) == ["E8", "E8"], g0["factors"]

    # ---- Borel-de Siebenthal maximal subgroups of E8, read off the root system.
    # These are the textbook regular maximal subalgebras; the root COUNT is the invariant.
    BDS = [("(1,0^7)", [F(1)] + [F(0)] * 7, ["E8", "SO(16)"], 112),
           ("(2/3,-1/3,-1/3,0^5)", [F(2, 3), F(-1, 3), F(-1, 3)] + [F(0)] * 5,
            ["E6", "E8", "SU(3)"], 78),
           ("(1/5)(4,-1^4,0^3)", [F(4, 5)] + [F(-1, 5)] * 4 + [F(0)] * 3,
            ["E8", "SU(5)", "SU(5)"], 40),
           ("(1/6)(1^5,-5,0,0)", [F(1, 6)] * 5 + [F(-5, 6), F(0), F(0)],
            ["E8", "SU(2)", "SU(3)", "SU(6)"], 38),
           ("(1/2)^8 [in Lambda]", [F(1, 2)] * 8, ["E8", "E8"], 240)]
    out["bds"] = {}
    for lab, V0, names, nr in BDS:
        V = list(V0) + [F(0)] * 8
        g = analyse_group(V)
        got = sorted(f["name"] for f in g["factors"])
        out["bds"][lab] = (got, g["n_roots"] - 240)
        assert got == names, (lab, got, names)
        assert g["n_roots"] - 240 == nr, (lab, g["n_roots"] - 240, nr)

    # ---- level-1 rep identification on a KNOWN case: SU(5) x SU(5) subset E8.
    V = [F(4, 5)] + [F(-1, 5)] * 4 + [F(0)] * 3 + [F(0)] * 8
    g = analyse_group(V)
    attach_orders(g)
    # STRONG invariant: decompose the 240 roots of the FIRST E8 under the local
    # SU(5) x SU(5) and reproduce the textbook branching
    #   248 = (24,1) + (1,24) + (5,10) + (10,5bar) + (5bar,10bar) + (10bar,5).
    # Root-level (Cartans excluded) that is 20+20 + 50+50+50+50 = 240.
    from collections import Counter
    su5 = [f for f in g["factors"] if f["name"] == "SU(5)"]
    assert len(su5) == 2, [f["name"] for f in g["factors"]]
    bad, br = 0, Counter()
    for p in e8xe8_roots()[:240]:
        tags = []
        for f in su5:
            rr = rep_of(p, f, g["simple"])
            assert rr["ok"], rr
            nm = rr.get("name") or ("adj" if rr["level"] == 2 else str(rr["hw"]))
            if nm != "adj" and not rr["level1_ok"]:
                bad += 1
            tags.append(nm)
        br[tuple(tags)] += 1
    out["su5xsu5_branching_of_240"] = {"%s,%s" % k: v for k, v in sorted(br.items())}
    out["su5_level_violations"] = bad
    assert bad == 0, bad
    assert sum(br.values()) == 240
    exp = {("adj", "1"): 20, ("1", "adj"): 20, ("5", "10"): 50, ("10", "5bar"): 50,
           ("5bar", "10bar"): 50, ("10bar", "5"): 50}
    assert dict(br) == exp, (dict(br), exp)
    if verbose:
        for k, v in out.items():
            print("  %-24s %s" % (k, v))
    return out


