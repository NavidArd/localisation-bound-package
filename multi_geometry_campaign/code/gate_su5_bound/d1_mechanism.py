HERE = os.path.dirname(os.path.abspath(__file__))
CAMP = os.path.dirname(os.path.dirname(HERE))
PHASE = os.path.join(CAMP, "code", "su5_ten_bound")
sys.path.insert(0, PHASE)
OUT = os.path.join(CAMP, "data", "gate_su5_bound")

ROLES10 = {"Q", "uc", "ec", "Qbar", "ucbar", "ecbar"}
ROLES5 = {"dc", "L", "Hu", "dcbar"}

GEOM = {
    "Z2xZ4_1_1": dict(lib="z2xz4_sweep", mod="z24sw_lib", M=2, N=4,
                      census=os.path.join(CAMP, "data", "z2xz4_sweep", "raw", "census")),
    "Z3xZ6_1_1": dict(lib="z3xz6_sweep", mod="z36sw_lib", M=3, N=6,
                      census=os.path.join(CAMP, "data", "z3xz6_sweep", "raw", "census")),
}

_S = None
_R2 = None
_ROOTSET = None


def _init():
    global _S, _R2, _ROOTSET
    import s5lib
    _S = s5lib
    _R2 = np.array([[int(2 * x) for x in a] for a in _S.e8xe8_roots()], dtype=np.int64)
    _ROOTSET = set(_S.e8xe8_roots())


# ------------------------------------------------------------------ lattice membership
def in_lam(v):
    """v (16 Fractions) in Lambda_{E8} x Lambda_{E8}?  Independent re-implementation."""
    for h in (0, 8):
        blk = v[h:h + 8]
        fr = [x % 1 for x in blk]
        if all(x == 0 for x in fr):
            pass
        elif all(x == F(1, 2) for x in fr):
            pass
        else:
            return False
        if sum(blk) % 2 != 0:
            return False
    return True


# ------------------------------------------------------------------ the SM Weyl group
def weyl_sm(gens):
    """All elements of the group generated by reflections in `gens` (simply-laced roots),
    returned as a list of callables acting on 16-vectors.  Represented as words; the group
    is tiny (S3 x S2 = 12) so closure by action on a generic probe is exact."""
    def refl(a):
        return lambda x, a=a: tuple(xi - _S.dot(x, a) * ai for xi, ai in zip(x, a))
    G = [refl(a) for a in gens]
    probe = tuple(F(7 ** i + 3 * i + 1, 11 ** (i + 1)) for i in range(16))
    words = [[]]
    seen = {probe: 0}
    out = [lambda x: tuple(x)]
    i = 0
    while i < len(words):
        w = words[i]
        i += 1
        for gi, g in enumerate(G):
            nw = w + [gi]
            v = probe
            for k in nw:
                v = G[k](v)
            if v in seen:
                continue
            seen[v] = len(words)
            words.append(nw)

            def f(x, nw=tuple(nw)):
                for k in nw:
                    x = G[k](x)
                return tuple(x)
            out.append(f)
    return out


def worker(args):
    path, geom, cap = args
    if _S is None:
        _init()
    G = GEOM[geom]
    sys.path.insert(0, os.path.join(CAMP, "code", G["lib"]))
    Z = __import__(G["mod"])
    S = _S
    allr = S.e8xe8_roots()

    acc = dict(
        models=0, skipped=Counter(), cells=0,
        # M5 hidden multiplicity
        hid_by_fam=defaultdict(Counter),          # fam -> Counter(hid)
        hid10_offenders=[], hid10_n=0,
        hid_by_fam_R=defaultdict(Counter),        # "fam|R" -> Counter(hid)
        # record-count vs hidden-weighted multiplicity per (cell, role)
        mult_rec_by_fam=defaultdict(Counter),
        mult_hid_by_fam=defaultdict(Counter),
        multR_rec=defaultdict(Counter), multR_hid=defaultdict(Counter), gram_fail=0,
        # M1..M4 on doubled pairs
        pairs=0, pairs_by_fam=Counter(),
        M1_fail=0, M2_fail=0, M3_notinlam=0, M3_zero=0, M3_notperp=0,
        M3_odd=0, M3_lt2=0, M4_notroot=0, M4_norm=Counter(),
        M3_cs_fail=0,
        fail_examples=[],
        # sanity
        R_by_fam=defaultdict(Counter),
        w2_by_fam=defaultdict(Counter),
    )
    txt = gzip.open(path, "rt", errors="replace").read()
    nm = 0
    for lab, blk in Z.split_models(txt):
        if cap and nm >= cap:
            break
        pre = blk.split("Analyzing")[0]
        try:
            if geom == "Z2xZ4_1_1":
                spec = Z.parse_spectrum(pre, M=G["M"], N=G["N"])
                factors = Z.parse_gauge_factors(blk)
                cfgs = Z.parse_smconfig(blk)
                if not cfgs or cfgs[0][0] is None or not spec:
                    acc["skipped"]["no_smconfig"] += 1
                    continue
                tY, tbl = cfgs[0]
                printed = defaultdict(int)
                for row in tbl:
                    printed[(row[0], row[1], row[2])] += row[3]
                pos = Z.observable_positions(spec, tY, factors, dict(printed))
                if pos is None:
                    acc["skipped"]["closure_failed"] += 1
                    continue
                a3, a2, sY0 = pos
                roles, diag = Z.role_census(spec, tY, a3, a2, sY0)
            else:
                spec = Z.parse_spectrum(pre)
                gauge = Z.parse_gauge(blk)
                if gauge["tY"] is None or not spec:
                    acc["skipped"]["no_hypercharge"] += 1
                    continue
                pos = Z.observable_positions(spec, gauge["tY"], gauge)
                if pos is None:
                    acc["skipped"]["closure_failed"] += 1
                    continue
                a3, a2, sY0, tY, bi = pos
                roles, diag = Z.role_census(spec, tY, a3, a2, sY0)
        except Exception as e:                                          # noqa: BLE001
            acc["skipped"]["parse_error:%s" % type(e).__name__] += 1
            continue
        nm += 1
        acc["models"] += 1

        cells = defaultdict(list)
        for l, r in spec.items():
            if r["p_sh"] is None or r["chir"] != "l":
                continue
            cells[(tuple(r["kl"]), tuple(r["fp"]) if r["fp"] else None)].append(r)

        # --- 4D gauge group -> SM Cartan span (same construction as the phase, so that a
        #     disagreement here is a disagreement about physics, not about bookkeeping)
        inter = None
        for key, recs in cells.items():
            V = recs[0]["p_sh"]
            D = 1
            for x in V:
                D = D * x.denominator // np.gcd(D, x.denominator)
            m = ((_R2 @ np.array([int(x * D) for x in V], dtype=np.int64))
                 % (2 * D)) == 0
            inter = m if inter is None else (inter & m)
        R4 = [allr[i] for i in np.nonzero(inter)[0]] if inter is not None else []
        if not R4:
            acc["skipped"]["no_4d_roots"] += 1
            continue
        Sp4 = S.simple_roots(R4)
        comps4, adj4 = S._components(Sp4)
        qrec = [r for r in spec.values()
                if roles.get(r["label"], {}).get("role") in ("Q", "Qbar")]
        drec = [r for r in spec.values()
                if roles.get(r["label"], {}).get("role") in ("dc", "dcbar")]
        lrec = [r for r in spec.values()
                if roles.get(r["label"], {}).get("role") in ("L", "Hu")]
        f3 = f2 = None
        for c_ in comps4:
            kind, rk = S._classify(c_, adj4, Sp4)
            so = [Sp4[i] for i in c_]
            if kind == "A" and rk == 2 and (qrec or drec):
                if all(any(S.dot(x["p_sh"], a) != 0 for a in so) for x in qrec + drec):
                    f3 = so if f3 is None else "AMBIG"
            if kind == "A" and rk == 1 and (qrec or lrec):
                if all(any(S.dot(x["p_sh"], a) != 0 for a in so) for x in qrec + lrec):
                    f2 = so if f2 is None else "AMBIG"
        if not (isinstance(f3, list) and isinstance(f2, list)):
            acc["skipped"]["smbasis_fail"] += 1
            continue
        smbasis = list(f3) + list(f2) + [tuple(tY)]
        WG = weyl_sm(list(f3) + list(f2))

        for key, recs in cells.items():
            (kl, fp) = key
            if tuple(kl) == (0, 0):
                continue
            acc["cells"] += 1
            byrole = defaultdict(list)
            for r in recs:
                ro = roles.get(r["label"], {}).get("role")
                if ro is None:
                    continue
                byrole[ro].append(r)
            for ro, rs in byrole.items():
                fam = "10" if ro in ROLES10 else ("5bar" if ro in ROLES5 else "?")
                if fam == "?":
                    continue
                # ---- M5: hidden multiplicity
                hidsum = 0
                for r in rs:
                    hid = 1
                    for k, dd in enumerate(r["rep"]):
                        if k not in (a3, a2):
                            hid *= abs(dd)
                    hidsum += hid
                    B = S.dot(r["p_sh"], r["p_sh"]) / 2
                    w2 = S.proj_norm2(r["p_sh"], smbasis)
                    Rv = 2 * B - w2
                    acc["R_by_fam"][fam][str(Rv)] += 1
                    acc["w2_by_fam"][fam][str(w2)] += 1
                    acc["hid_by_fam"][fam][hid] += 1
                    acc["hid_by_fam_R"]["%s|%s" % (fam, Rv)][hid] += 1
                    if fam == "10" and hid > 1:
                        acc["hid10_n"] += 1
                        if len(acc["hid10_offenders"]) < 25:
                            acc["hid10_offenders"].append(dict(
                                model=lab, kl=list(kl), fp=list(fp) if fp else None,
                                role=ro, hid=hid, rep=list(r["rep"]),
                                a3=a3, a2=a2, R=str(Rv), B=str(B),
                                file=os.path.basename(path)))
                acc["mult_rec_by_fam"][fam][len(rs)] += 1
                acc["mult_hid_by_fam"][fam][hidsum] += 1
                # ---- M6: the Gram bound.  n states of norm^2 R with pairwise
                # differences of norm^2 2 have Gram I + (R-1)J, PSD iff n <= 1/(1-R).
                # Since |Delta|^2 <= 4R < 4 at every measured R, |Delta|^2 = 2 is forced,
                # so the bound applies to the HIDDEN-WEIGHTED state count, not the record
                # count.  Keyed by the largest R at the (cell, role).
                Rmax = max(2 * (S.dot(r["p_sh"], r["p_sh"]) / 2)
                           - S.proj_norm2(r["p_sh"], smbasis) for r in rs)
                acc["multR_rec"]["%s|%s" % (fam, Rmax)][len(rs)] += 1
                acc["multR_hid"]["%s|%s" % (fam, Rmax)][hidsum] += 1
                if Rmax < 1 and hidsum * (1 - Rmax) > 1:
                    acc["gram_fail"] += 1
                    if len(acc["fail_examples"]) < 20:
                        acc["fail_examples"].append(
                            dict(test="M6_gram", model=lab, kl=list(kl),
                                 fp=list(fp) if fp else None, role=ro,
                                 n=hidsum, R=str(Rmax),
                                 bound=str(F(1, 1) / (1 - Rmax)),
                                 file=os.path.basename(path)))

                # ---- M1..M4 on genuinely doubled pairs (record level)
                if len(rs) < 2:
                    continue
                for i in range(len(rs)):
                    for j in range(i + 1, len(rs)):
                        p = tuple(rs[i]["p_sh"])
                        q = tuple(rs[j]["p_sh"])
                        acc["pairs"] += 1
                        acc["pairs_by_fam"][fam] += 1
                        w2p = S.proj_norm2(p, smbasis)
                        w2q = S.proj_norm2(q, smbasis)
                        if w2p != w2q:
                            acc["M1_fail"] += 1
                            if len(acc["fail_examples"]) < 20:
                                acc["fail_examples"].append(
                                    dict(test="M1", model=lab, kl=list(kl), role=ro,
                                         w2p=str(w2p), w2q=str(w2q)))
                            continue
                        Bp = S.dot(p, p) / 2
                        Bq = S.dot(q, q) / 2
                        Rp = 2 * Bp - w2p
                        Rq = 2 * Bq - w2q
                        # find sigma in W_SM aligning the SM weights
                        good = None
                        for sg in WG:
                            qq = sg(q)
                            if all(S.dot(qq, b) == S.dot(p, b) for b in smbasis):
                                good = qq
                                break
                        if good is None:
                            acc["M2_fail"] += 1
                            if len(acc["fail_examples"]) < 20:
                                acc["fail_examples"].append(
                                    dict(test="M2", model=lab, kl=list(kl), role=ro,
                                         p=[str(x) for x in p], q=[str(x) for x in q]))
                            continue
                        D = tuple(a - b for a, b in zip(p, good))
                        n2 = S.dot(D, D)
                        if all(x == 0 for x in D):
                            acc["M3_zero"] += 1
                            if len(acc["fail_examples"]) < 20:
                                acc["fail_examples"].append(
                                    dict(test="M3_zero", model=lab, kl=list(kl),
                                         fp=list(fp) if fp else None, role=ro,
                                         p=[str(x) for x in p],
                                         labels=[rs[i]["label"], rs[j]["label"]],
                                         file=os.path.basename(path)))
                            continue
                        if not in_lam(D):
                            acc["M3_notinlam"] += 1
                            if len(acc["fail_examples"]) < 20:
                                acc["fail_examples"].append(
                                    dict(test="M3_lam", model=lab, kl=list(kl), role=ro,
                                         D=[str(x) for x in D], n2=str(n2)))
                            continue
                        if any(S.dot(D, b) != 0 for b in smbasis):
                            acc["M3_notperp"] += 1
                            continue
                        if n2.denominator != 1 or int(n2) % 2 != 0:
                            acc["M3_odd"] += 1
                            continue
                        if n2 < 2:
                            acc["M3_lt2"] += 1
                            continue
                        # Cauchy-Schwarz / theorem: |D|^2 <= (sqrt Rp + sqrt Rq)^2
                        t = n2 - Rp - Rq
                        if not (t <= 0 or 4 * Rp * Rq >= t * t):
                            acc["M3_cs_fail"] += 1
                        acc["M4_norm"][str(n2)] += 1
                        if n2 == 2 and D not in _ROOTSET:
                            acc["M4_notroot"] += 1
    for k in ("hid_by_fam", "hid_by_fam_R", "mult_rec_by_fam", "mult_hid_by_fam",
              "multR_rec", "multR_hid", "R_by_fam", "w2_by_fam"):
        acc[k] = {a: {str(x): y for x, y in b.items()} for a, b in acc[k].items()}
    for k in ("skipped", "M4_norm", "pairs_by_fam"):
        acc[k] = dict(acc[k])
    return acc


def merge(accs):
    out = defaultdict(int)
    dicts = ("hid_by_fam", "hid_by_fam_R", "mult_rec_by_fam", "mult_hid_by_fam",
             "multR_rec", "multR_hid", "R_by_fam", "w2_by_fam")
    flat = ("skipped", "M4_norm", "pairs_by_fam")
    o = {k: defaultdict(Counter) for k in dicts}
    fl = {k: Counter() for k in flat}
    lists = {"hid10_offenders": [], "fail_examples": []}
    ints = ("models", "cells", "pairs", "M1_fail", "M2_fail", "M3_notinlam", "M3_zero",
            "M3_notperp", "M3_odd", "M3_lt2", "M4_notroot", "M3_cs_fail", "hid10_n",
            "gram_fail")
    for a in accs:
        for k in ints:
            out[k] += a[k]
        for k in dicts:
            for x, d in a[k].items():
                o[k][x].update(d)
        for k in flat:
            fl[k].update(a[k])
        for k in lists:
            lists[k] += a[k][:10]
    res = {k: out[k] for k in ints}
    for k in dicts:
        res[k] = {x: dict(d) for x, d in o[k].items()}
    for k in flat:
        res[k] = dict(fl[k])
    for k in lists:
        res[k] = lists[k][:40]
    return res


def main():
    geom = sys.argv[1] if len(sys.argv) > 1 else "Z2xZ4_1_1"
    nseg = int(sys.argv[2]) if len(sys.argv) > 2 else 0
    cap = int(sys.argv[3]) if len(sys.argv) > 3 else 0
    files = sorted(glob.glob(os.path.join(GEOM[geom]["census"], "*.txt.gz")))
    if nseg:
        files = files[:nseg]
    tasks = [(f, geom, cap) for f in files]
    with mp.Pool(6, initializer=_init) as pool:
        accs = pool.map(worker, tasks)
    res = merge(accs)
    res["geometry"] = geom
    res["n_segments"] = len(files)
    with open(os.path.join(OUT, "d1_mechanism_%s.json" % geom), "w") as fh:
        json.dump(res, fh, indent=1, default=str)
    print(json.dumps({k: v for k, v in res.items()
                      if k not in ("hid10_offenders", "fail_examples")},
                     indent=1, default=str)[:9000])
    print("\nHID>1 ON 10-ROLES:", res["hid10_n"])
    for e in res["hid10_offenders"][:6]:
        print("   ", e)
    print("FAIL EXAMPLES:", len(res["fail_examples"]))
    for e in res["fail_examples"][:8]:
        print("   ", e)


if __name__ == "__main__":
    main()
