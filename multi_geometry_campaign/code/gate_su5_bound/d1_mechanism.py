"""GATE su5_ten_bound -- D1/D2/D3: test the DERIVATION'S MECHANISM, not its conclusion.

The phase's verify.py tests only the INEQUALITY sqrt(R)+sqrt(R') >= sqrt(2) on pairs that
the census reports.  Because 10-roles never double, that test never fires on the 10 side;
and on the 5bar side it is satisfied with huge margin, so it is close to vacuous.  The
mechanism itself -- every step of the proof -- has never been tested on data.

This script tests the proof step by step on the pairs where it CAN be tested: the tens of
thousands of cells where a 5bar-role genuinely doubles.

For each cell and each role with >= 2 left-chiral records p, p':

  M1  |P_W p|^2 == |P_W p'|^2                       (H4: same role => same |w|^2)
  M2  w_p and w_p' lie in ONE orbit of W_SM = <s_a1, s_a2, s_b>   (the WLOG step exists)
  M3  for SOME sigma in W_SM with P_W sigma(p') = P_W p:
        Delta = p - sigma(p') is NON-ZERO,
        Delta is in Lambda_{E8xE8}                  (D2: the lattice step)
        Delta . (SM basis) == 0                     (P_W Delta = 0)
        |Delta|^2 is a POSITIVE EVEN integer >= 2   (H1: evenness)
        |Delta|^2 <= (sqrt(R)+sqrt(R'))^2           (Cauchy-Schwarz, the theorem)
  M4  since 4R < 4 for every measured R, |Delta|^2 MUST equal 2 exactly: Delta is a ROOT.
      Checked against the explicit 480-root list.

and independently:

  M5  HIDDEN MULTIPLICITY.  role_census carries `mult` = the product of the dimensions
      under the NON-SM gauge factors; verify.py counts RECORDS (`rmult[ro] += 1`) and
      ignores it.  A 10-role record that is a doublet of a hidden SU(2) IS two states with
      the same SM role at one cell, differing by a hidden root -- exactly the theorem's
      forbidden configuration and exactly the phase's own loophole condition 2.
      The theorem therefore PREDICTS: no 10-role field anywhere with R < 1/2 may carry
      hidden multiplicity > 1.  This is a hard falsifiable test the phase never ran.

  M6  Gram bound.  n vectors of norm^2 R with pairwise differences of norm^2 2 have Gram
      I + (R-1)J, PSD iff 1 + n(R-1) >= 0, i.e. n <= 1/(1-R).  Compare with the measured
      maximum multiplicity per (family, R).

Output: data/gate_su5_bound/d1_mechanism_<geom>.json
"""
from __future__ import annotations

import os

for _v in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
    os.environ[_v] = "1"

import glob                                                             # noqa: E402
